import type { FaceConfigState } from "../face-engine/faceConfigState";
import { buildEmotionTriangulationFromPoints } from "../face-engine/emotionTriangulationLive";
import { fmtCppFloat } from "./format";

export function emitEmotionTriangulationH(config: FaceConfigState): string {
    const tri = buildEmotionTriangulationFromPoints(config.emotionNames, config.emotionPoints);
    const anchorLines = tri.anchors
        .map(
            a =>
                `    { ${fmtCppFloat(a.v)}, ${fmtCppFloat(a.a)}, EmotionSystem::NamedEmotion::${a.emotion} },`
        )
        .join("\n");
    const triangleLines = tri.triangles
        .map(t => `    { ${t[0]}, ${t[1]}, ${t[2]} },`)
        .join("\n");

    return `// !!! GENERATED FILE - DO NOT EDIT !!!
//
// Generated by face-editor POST /api/saveData (delaunator from FACE_CONFIG_DATA kEmotionPoints).
//
// Anchors: ${tri.anchors.length}
// Triangles: ${tri.triangles.length}

#pragma once

#include <Arduino.h>

#include "EmotionSystem.h"

namespace EmotionSystem {

struct Anchor {
  float v;
  float a;
  NamedEmotion emotion;
};

struct Triangle {
  uint16_t i0;
  uint16_t i1;
  uint16_t i2;
};

static constexpr size_t kAnchorCount = ${tri.anchors.length};
static constexpr Anchor kAnchors[kAnchorCount] = {
${anchorLines}
};

static constexpr size_t kTriangleCount = ${tri.triangles.length};
static constexpr Triangle kTriangles[kTriangleCount] = {
${triangleLines}
};

}  // namespace EmotionSystem
`;
}
